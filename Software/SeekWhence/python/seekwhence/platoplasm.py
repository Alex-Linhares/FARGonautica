"""The platoplasm: ideal atoms and the eight non-atomic ideal types [M86 pp. 48-59].

"Currently, the platoplasm houses the ideal types -- the primitive, built-in notions available
to the system for use in constructing its view of a sequence" [M86 p. 48]. This module holds
the ideal atoms with their predecessor and successor [M86 pp. 48-49], the eight types with
their hierarchy (repeater, generate, process, fence) [M86 pp. 54-55], their generating
functions [M86 pp. 54, 56], their process functions [M86 pp. 54, 68], the membership test of
a form with parameters (`(Y-group 1 5)` [M86 p. 55]), purity [M86 p. 69], strictness
[M86 p. 59], and the hit semantics of a form: what each type returns when "queried -- or
'hit', as we say" [M86 p. 49], one value per hit [M86 pp. 50-58]. The boxes that make a
hypothesis's form active (item 07) are built on `hits` and must agree with it.

The module also holds what ch. 3 calls "the system's slipping network -- which is all within
the platoplasm" [M86 p. 90]: the s-links with their slipperiness [M86 pp. 90-91], the
"level-spanning" network of each concept's manifestations and actualizations and its "lists
of pulling and pushing bonds" [M86 p. 90], a bond's strength "in the environment" of a class
[M86 pp. 99-100], and the strict classes [M86 p. 99]. The tables come from `Config`
(DECISIONS D-038, D-039, D-040) and are read once per run.
"""

from dataclasses import dataclass, field

from seekwhence.config import IDEAL_TYPES, Config
from seekwhence.forms import (
    GROUP_TYPES, LIST_TYPES, REPEATER_TYPES, Form, Shared, flatten, is_form, is_int)


# ---- ideal atoms --------------------------------------------------------------------------

@dataclass(eq=False)
class IdealAtom:
    """"The ideal-atoms are Seek-Whence analogues to the integers entered at the keyboard.
    An ideal-atom has predecessor and successor values, its own value, and manifestations in
    the cytoplasm" [M86 p. 48]. The manifestations are glints [M86 pp. 49, 61] and only
    glints: "only glints are referenced as manifestations of ideal atoms" [M86 p. 49]."""

    value: int
    manifestations: list = field(default_factory=list)

    @property
    def name(self) -> str:
        """`ideal5`, as the thesis names them [M86 p. 48]."""
        return f"ideal{self.value}"

    @property
    def predecessor_value(self):
        """The value before this one, or None: "'ideal0' has no predecessor" [M86 p. 49]."""
        return self.value - 1 if self.value > 0 else None

    @property
    def successor_value(self) -> int:
        """The value after this one: ideal0 "has 'ideal1' as successor" [M86 p. 49]."""
        return self.value + 1


# ---- the eight non-atomic ideal types -----------------------------------------------------

@dataclass(eq=False)
class IdealType:
    """One of the eight non-atomic ideal types [M86 pp. 49-55], its place in the hierarchy
    and its lists.

    `category` is repeater, generate, process or fence [M86 pp. 54-55]; `has_generator` says
    whether the actual value "can be generated by the associated 'generating function'"
    [M86 p. 54] (repeaters and generate types), `has_process` whether the type "possesses a
    'process'" [M86 pp. 54, 68] (all but the fence types). `manifestations` are the gloms
    dubbed of this type [M86 p. 69], `actualizations` the gnoths of this class [M86 p. 77]:
    together "the lists each Platonic concept maintains of its manifestations and
    actualizations" [M86 p. 90].

    For reformulation [M86 ch. 3]: `s_links` maps each s-link neighbour to the link's
    slipperiness, "a number between 0 (non-slippery) and 1 (perfectly slippery)" [M86 p. 90],
    in the table's order (DECISION D-038); `pulls` and `pushes` are the "lists of pulling and
    pushing bonds, bonds which the concept can use to group or separate sequence terms"
    [M86 p. 90], each keyed by (bond type, modifier) with "a strength from 1 to 10"
    [M86 p. 91], pushes held with their negative sign (DECISION D-039); `strict` says whether
    the class "is very strict in the sense that it is difficult to generalize without moving
    to a new class altogether" [M86 p. 99] (DECISION D-040).
    """

    name: str
    category: str
    format: str
    manifestations: list = field(default_factory=list)
    actualizations: list = field(default_factory=list)
    s_links: dict = field(default_factory=dict)
    pulls: dict = field(default_factory=dict)
    pushes: dict = field(default_factory=dict)
    strict: bool = False

    @property
    def has_generator(self) -> bool:
        """Repeater and generate types generate their values [M86 p. 54]; the process and
        fence types have "no generator" [M86 pp. 54-55]."""
        return self.category in ("repeater", "generate")

    @property
    def has_process(self) -> bool:
        """"all but the fence-type plato-classes (Tuple and Cycle) possess a 'process'"
        [M86 p. 68]."""
        return self.category != "fence"

    def bond_value(self, type: str, modifier: str) -> int:
        """A bond type's strength in this class's environment: positive for a listed
        pull-bond, negative for a listed push-bond [M86 pp. 91, 100], and 0 for a bond type
        the class lists neither way (the `(bond2 0)` of an adjacent Pred bond under S-group
        [M86 p. 175]; DECISION D-039). `type` is `Same`, `Succ`, `Pred` or `Same-span`."""
        key = (type, modifier)
        if key in self.pulls:
            return self.pulls[key]
        return self.pushes.get(key, 0)

    @property
    def strongest_pull(self) -> int:
        """"the strongest pull-bond strength for the reigning type" [M86 p. 105], from which
        the Reformulator's first threshold is taken; 0 for a class with no pull-bonds."""
        return max(self.pulls.values(), default=0)

    def neighbours(self) -> tuple:
        """The classes "connected to it by s-links in the platoplasm", "the primary
        'pretenders to the throne'" [M86 p. 103], in the table's order (DECISION D-038)."""
        return tuple(self.s_links)

    @property
    def most_slippery(self) -> str | None:
        """The neighbour with the most slippery s-link, the class a strict reigning class
        slips to at once (DECISION D-040); ties go to the first listed; None for a class
        without s-links."""
        best = None
        for other, slipperiness in self.s_links.items():
            if best is None or slipperiness > self.s_links[best]:
                best = other
        return best


# The hierarchy "of categories, each of which captures an important organizing notion for
# the Seek-Whence world" [M86 p. 54], from the strictest down [M86 p. 59].
CATEGORIES = ("repeater", "generate", "process", "fence")

# (name, category, format) in the thesis's order [M86 pp. 50-55].
TYPE_TABLE = (
    ("Constant", "repeater", "(Constant arg)"),
    ("Countup", "repeater", "(Countup n)"),
    ("C-group", "generate", "(C-group start length)"),
    ("S-group", "generate", "(S-group start length)"),
    ("P-group", "generate", "(P-group start length)"),
    ("Y-group", "process", "(Y-group [start] [length] actual)"),
    ("Cycle", "fence", "(Cycle actual)"),
    ("Tuple", "fence", "(Tuple actual)"),
)
assert tuple(row[0] for row in TYPE_TABLE) == IDEAL_TYPES

CATEGORY_OF = {name: category for name, category, _ in TYPE_TABLE}


def category(kind: str) -> str:
    """The hierarchy category of a type name [M86 pp. 54-55]."""
    return CATEGORY_OF[kind]


def members(cat: str) -> tuple:
    """The types in one category: "members: Constant, Countup" and so on [M86 pp. 54-55]."""
    return tuple(name for name, c, _ in TYPE_TABLE if c == cat)


def is_stricter(kind: str, other: str) -> bool:
    """Whether `kind` is higher in the hierarchy than `other`: a slip downward is to "a less
    strict class" [M86 p. 59]; the fence types are "the least restrictive types"
    [M86 p. 55]. Types in one category are not stricter than one another."""
    return CATEGORIES.index(category(kind)) < CATEGORIES.index(category(other))


def bond_key(type: str, field: str) -> str:
    """The key under which a bond's type is listed in the pull and push tables: its type for
    a bond on the print-value, and `Same-span` for a sameness bond on the span, the C-group's
    liking for "gloms having the same span" [M86 p. 91] (DECISION D-039)."""
    if field == "span":
        if type != "Same":
            raise ValueError(f"a span bond is a sameness bond, not {type}")
        return "Same-span"
    return type


class Platoplasm:
    """The platoplasm of one run: the ideal atoms, made as their values are met, and the
    eight ideal types with their manifestation and actualization lists [M86 pp. 48-49, 69,
    77], their s-links [M86 pp. 90-91], their pull and push bond lists [M86 pp. 91, 100] and
    their strictness [M86 p. 99], read from the `Config` tables (DECISIONS D-038, D-039,
    D-040) when the run starts: the slipperiness values "can be changed during processing,
    although the current system does not do so" and the strengths "could be, but in
    practice are not, changed by the system" [M86 p. 91]. Nothing else is in it: new
    notions "may eventually come to be housed in the platoplasm" [M86 p. 48], but are not."""

    def __init__(self, config: Config | None = None):
        self.config = config if config is not None else Config()
        self.atoms: dict = {}
        self.types: dict = {name: IdealType(name, cat, fmt) for name, cat, fmt in TYPE_TABLE}
        # The tables are checked as they are read (a network built from a table checks
        # every name and every value at build time): a slipperiness is
        # "a number between 0 (non-slippery) and 1 (perfectly slippery)" [M86 p. 90], a
        # bond strength "from 1 to 10" [M86 p. 91], negative for a push (DECISION D-039).
        for frm, to, slipperiness in self.config.s_links:
            self._known(frm), self._known(to)
            if frm == to or not 0 <= slipperiness <= 1:
                raise ValueError(f"bad s-link {(frm, to, slipperiness)!r}")
            self.types[frm].s_links[to] = slipperiness
        for kind, type, modifier, value in self.config.bond_values:
            self._known(kind)
            if not 1 <= abs(value) <= 10:
                raise ValueError(f"bad bond value {(kind, type, modifier, value)!r}")
            lists = self.types[kind].pulls if value > 0 else self.types[kind].pushes
            lists[(type, modifier)] = value
        for kind in self.config.strict_classes:
            self._known(kind)
            self.types[kind].strict = True

    def _known(self, kind: str) -> None:
        if kind not in self.types:
            raise ValueError(f"not an ideal type: {kind!r}")

    def atom(self, value: int) -> IdealAtom:
        """The ideal atom of a nonnegative integer, created the first time it is asked for
        [M86 p. 48]."""
        if not is_int(value) or value < 0:
            raise ValueError(f"ideal atoms are nonnegative integers, got {value!r}")
        if value not in self.atoms:
            self.atoms[value] = IdealAtom(value)
        return self.atoms[value]

    def predecessor(self, atom: IdealAtom):
        """The atom's predecessor, or None for ideal0 [M86 pp. 48-49]."""
        return None if atom.predecessor_value is None else self.atom(atom.predecessor_value)

    def successor(self, atom: IdealAtom) -> IdealAtom:
        """The atom's successor [M86 pp. 48-49]."""
        return self.atom(atom.successor_value)

    def add_manifestation(self, value: int, glint) -> IdealAtom:
        """List a glint "as a manifestation, or cyto-level analogue, of the appropriate
        ideal-atom in the platoplasm" [M86 p. 61]."""
        atom = self.atom(value)
        atom.manifestations.append(glint)
        return atom

    def type(self, kind: str) -> IdealType:
        """The ideal type of a name [M86 pp. 49-53]."""
        return self.types[kind]

    # ---- the level-spanning network [M86 p. 90] ---------------------------------------------

    def manifest(self, kind: str, glom) -> None:
        """List a dubbed glom on its ideal: "the Platonic ideal has this glom added to its
        list of manifestations" [M86 p. 69]."""
        self.types[kind].manifestations.append(glom)

    def actualize(self, kind: str, gnoth) -> None:
        """List a gnoth on its class: "The actualizations are socrato-level structures which
        have similarly been identified as representatives of the concept at that level"
        [M86 p. 90]."""
        self.types[kind].actualizations.append(gnoth)

    def forget(self, structure) -> None:
        """Drop a destroyed structure from every manifestation and actualization list: a
        manifestation is a cyto-level structure "which [has] been dubbed" [M86 p. 90], so a
        glom that no longer exists is no manifestation (DECISION D-059)."""
        for ideal in self.types.values():
            ideal.manifestations = [m for m in ideal.manifestations if m is not structure]
            ideal.actualizations = [a for a in ideal.actualizations if a is not structure]

    # ---- the slipping network [M86 pp. 90-91] ------------------------------------------------

    def s_link(self, frm: str, to: str) -> float:
        """The slipperiness of the s-link from one class to another, "my estimate of the
        system's proclivity to move from the given concept to the neighbor" [M86 p. 90]:
        S-group to Countup 0.1, to Tuple 0.4 [M86 pp. 90-91]; 0 where there is no link
        (DECISION D-038)."""
        return self.types[frm].s_links.get(to, 0.0)

    def neighbours(self, kind: str) -> tuple:
        """The s-link neighbours of a class [M86 pp. 90, 103]: "S-group has s-links to Countup,
        C-group, Y-group, Cycle, and Tuple" [M86 p. 90]."""
        return self.types[kind].neighbours()

    def is_strict(self, kind: str) -> bool:
        """Whether a reigning class "is very strict in the sense that it is difficult to
        generalize without moving to a new class altogether", so that "slipping is chosen
        immediately" [M86 p. 99] (DECISION D-040)."""
        return self.types[kind].strict

    # ---- bonds in the environment of a class [M86 pp. 99-100] ------------------------------

    def bond_value(self, kind: str, bond) -> int:
        """A bond "assessed in the environment of this class -- assigned a strength which
        depends on the class in question as well as on the type of the bond" [M86 p. 99]:
        under S-group an adjacent successor bond is +10 and a remote sameness bond -5
        [M86 p. 101], an adjacent predecessor bond 0 [M86 p. 175]; under Y-group a remote
        sameness bond is 10 [M86 p. 104] (DECISION D-039). `bond` has `type`, `field` and
        `modifier` (a `cytoplasm.Bond`)."""
        return self.types[kind].bond_value(bond_key(bond.type, bond.field), bond.modifier)

    def pull_bonds(self, kind: str) -> dict:
        """The class's pull-bonds, "Bonds which a Platonic class might use to hold groups
        together" [M86 p. 91], (type, modifier) -> strength 1 to 10."""
        return dict(self.types[kind].pulls)

    def push_bonds(self, kind: str) -> dict:
        """The class's push-bonds, "those it tends to use to separate groups" [M86 p. 91],
        (type, modifier) -> strength -1 to -10."""
        return dict(self.types[kind].pushes)

    def strongest_pull(self, kind: str) -> int:
        """"the strongest pull-bond strength for the reigning type" [M86 p. 105]: 10 for
        S-group, so that the first threshold is 8.0 [M86 p. 174]."""
        return self.types[kind].strongest_pull


# ---- generating functions [M86 pp. 54, 56] -------------------------------------------------

def generate(kind: str, start, length: int) -> tuple:
    """The generating function of a generate type: "Given a typename and the start and length
    parameters (e.g., (C-group 1 3)), the actual value (e.g., (1 1 1)) can be generated"
    [M86 p. 54]: `(C-group 1 5)` is `(1 1 1 1 1)`, `(S-group 2 3)` is `(2 3 4)`,
    `(P-group 9 4)` is `(9 8 7 6)` [M86 p. 56].

    A C-group's start may be any value, which is copied [M86 p. 51]; an S-group's or
    P-group's must be an integer. A P-group that "would run to negative numbers" is
    "undefined" [M86 p. 52] and raises `ValueError` (DECISION D-006).
    """
    if kind not in GROUP_TYPES:
        raise ValueError(f"{kind} has no generating function of start and length")
    if not is_int(length) or length < 0:
        raise ValueError(f"a group's length must be a nonnegative integer, got {length!r}")
    if kind == "C-group":
        return tuple([start] * length)
    if not is_int(start):
        raise ValueError(f"{kind} needs an integer to start from, not {start!r}")
    step = 1 if kind == "S-group" else -1
    if kind == "P-group" and length > 0 and start - (length - 1) < 0:
        raise ValueError(f"(P-group {start} {length}) is undefined: would run to negative "
                         "numbers [M86 p. 52]")
    return tuple(start + step * i for i in range(length))


# ---- process functions [M86 pp. 54, 68] ----------------------------------------------------

def is_c_group(values) -> bool:
    """The C-group process: every element a copy of the first, "a number of copies of a
    given argument" [M86 p. 51]; `((1 5) (1 5) (1 5))` passes too [M86 p. 69]."""
    return len(values) > 0 and all(v == values[0] for v in values)


def is_s_group(values) -> bool:
    """The S-group process: "a given-length run of successive integers" [M86 p. 51]."""
    return (len(values) > 0 and all(is_int(v) for v in values)
            and all(b == a + 1 for a, b in zip(values, values[1:])))


def is_p_group(values) -> bool:
    """The P-group process: "a given-length downward progression of nonnegative integers"
    [M86 p. 52]."""
    return (len(values) > 0 and all(is_int(v) and v >= 0 for v in values)
            and all(b == a - 1 for a, b in zip(values, values[1:])))


def is_y_group(values) -> bool:
    """The Y-group process: "a given group of nonnegative integers, symmetric about the
    center" [M86 p. 52], "without reference to any information external to the group"
    [M86 p. 54]."""
    return len(values) > 0 and tuple(values) == tuple(reversed(tuple(values)))


def is_constant(values) -> bool:
    """A number string a Constant could return: one value repeated [M86 p. 50]
    (DECISION D-005: the repeaters' processes serve the Hypothesizer and the Gnoth-caster,
    never a Plato-scout)."""
    return len(values) > 0 and all(is_int(v) for v in values) and is_c_group(values)


def is_countup(values) -> bool:
    """A number string a Countup could return: "nonnegative integers in succession"
    [M86 p. 50] (DECISION D-005)."""
    return is_s_group(values) and values[0] >= 0


PROCESSES = {
    "Constant": is_constant, "Countup": is_countup,
    "C-group": is_c_group, "S-group": is_s_group, "P-group": is_p_group,
    "Y-group": is_y_group,
}


def passes(kind: str, values, flat: bool = True) -> bool:
    """Whether a number string "is an instantiation of the class" [M86 p. 68] by the class's
    process; for a fence class, which has no process, "if the glom is 'flat' -- has only
    glints as subgloms -- a 'pass by default' occurs" [M86 p. 69], and a non-flat one does
    not pass here (the Plato-evaluator's business, DECISION D-023)."""
    if kind in PROCESSES:
        return PROCESSES[kind](tuple(values))
    return bool(flat) and len(values) > 0


def purity(flat: bool) -> str:
    """"pure <--> an exact manifestation; flat; e.g., (1 1 1) secondary <--> not flat; e.g.,
    ((1 5) (1 5) (1 5))" [M86 p. 69]."""
    return "pure" if flat else "secondary"


def accepts(form: Form, values) -> bool:
    """Whether a number string is a representative of a form with parameters: `(Y-group 1 5)`
    "is sufficient to determine that (1 7 4 7 1) is such a Y-group whereas (1 8 2 5 1),
    (1 7 1), and (2 0 0 0 1) are not" [M86 p. 55].

    The class's process must pass (a fence class passes a flat string by default
    [M86 p. 69]); then every integer parameter is checked: a start against the first value,
    a length against the count, a fence form's elements against the values. A parameter that
    is a form (or a `Shared`) is not checked: the string's fit to a form with inner structure
    is the Template-applier's business [M86 pp. 74-75] (item 12). For Constant and Countup
    the argument is the start (DECISION D-005).
    """
    values = tuple(values)
    if not passes(form.kind, values, flat=all(is_int(v) for v in values)):
        return False
    if form.kind in LIST_TYPES and form.actual is not None:
        # The start and length of a form with elements are derived from them (D-001).
        if len(values) != len(form.actual):
            return False
        return all(not is_int(e) or e == v for e, v in zip(form.actual, values))
    if is_int(form.start) and (not values or values[0] != form.start):
        return False
    if is_int(form.length) and len(values) != form.length:
        return False
    return True


# ---- hits: what a form returns when queried [M86 pp. 49-58] ------------------------------

class _Hitter:
    """One node of a form made able to answer hits, with the epoch rule of DECISION D-003:
    hit twice within one hit of the whole form, it gives the value it computed the first
    time ("they can report this value until the next time they are hit" [M86 p. 85])."""

    def __init__(self, clock: list, compute, children: list = ()):
        self.clock = clock
        self.compute = compute
        self.children = list(children)
        self.epoch = None
        self.value = None

    def hit(self):
        if self.epoch != self.clock[0]:
            self.epoch = self.clock[0]
            self.value = self.compute()
        return self.value


def _hitter(form, clock: list, siblings: list) -> _Hitter:
    """Build the hitter of a form, an integer (a constant) or a `Shared` (the sibling it
    shares, DECISION D-002)."""
    if is_int(form):
        return _Hitter(clock, lambda: form)
    if isinstance(form, Shared):                 # the same node, reached by the arrow's path
        node = siblings[form.path[0]]
        for index in form.path[1:]:
            node = node.children[index]
        return node
    if not is_form(form):
        raise TypeError(f"not a form: {form!r}")
    kind = form.kind
    if kind == "Constant":                       # "always returns one value" [M86 p. 50]
        arg = _hitter(form.start, clock, [])
        state = []

        def constant():
            if not state:
                state.append(arg.hit())
            return state[0]
        return _Hitter(clock, constant, [arg])
    if kind == "Countup":                        # n, n + 1, n + 2, ... [M86 p. 50]
        arg = _hitter(form.start, clock, [])
        state = []

        def countup():
            if state:
                state[0] += 1
            else:
                first = arg.hit()
                if not is_int(first) or first < 0:
                    raise ValueError(f"(Countup {first!r}) must start at a nonnegative "
                                     "integer [M86 p. 50]")
                state.append(first)
            return state[0]
        return _Hitter(clock, countup, [arg])
    if kind in GROUP_TYPES:                      # (type start length) [M86 pp. 51-52]
        args = []
        for slot in form.elements:
            args.append(_hitter(slot, clock, args))
        start, length = args
        return _Hitter(clock, lambda: generate(kind, start.hit(), length.hit()), args)
    elements = []                                # (type [start] [length] actual) [M86 pp. 52-53]
    if form.actual is None:
        raise ValueError(f"{form} has no elements to hit [M86 p. 55]")
    for element in form.actual:
        elements.append(_hitter(element, clock, elements))
    if kind == "Cycle":                          # "one top-level element each time" [M86 p. 53]
        turn = [0]

        def cycle():
            element = elements[turn[0] % len(elements)]
            turn[0] += 1
            return element.hit()
        return _Hitter(clock, cycle, elements)
    return _Hitter(clock, lambda: tuple(e.hit() for e in elements), elements)


class Hitting:
    """A form made active, so that it can be hit again and again: "When such a form is
    queried -- or 'hit', as we say -- it returns a value" [M86 p. 49].

    `hit()` gives the next value: a single integer for a repeater [M86 p. 50] or a Cycle
    [M86 p. 53], a tuple for a group [M86 pp. 51-52], a Y-group [M86 p. 52] or a Tuple
    [M86 p. 53]. A nested form is hit each time the enclosing structure needs its value, so
    the Countup inside a group advances once per hit of the group [M86 p. 51] and the one
    inside a Cycle once per turn [M86 p. 53]; a shared structure is read once per hit of the
    whole form (DECISION D-003). `reset()` starts again from the beginning.
    """

    def __init__(self, form: Form):
        if not is_form(form):
            raise TypeError(f"not a form: {form!r}")
        self.form = form
        self.reset()

    def reset(self):
        """Start the form again from its first value, as a hypothesis's box is reset to
        predict from the beginning [M86 p. 81]."""
        self.clock = [0]
        self.count = 0
        self._top = _hitter(self.form, self.clock, [])

    def hit(self):
        """The next value of the form: "When such a form is queried -- or 'hit', as we say --
        it returns a value" [M86 p. 49]."""
        self.clock[0] += 1
        self.count += 1
        return self._top.hit()


def hits(form: Form, n: int) -> list:
    """The first n values a fresh form returns, "The results of successive hits" [M86 p. 49]:
    `(S-group 1 (Countup 2))` gives `(1 2)`, `(1 2 3)`, `(1 2 3 4)` [M86 p. 56]."""
    hitting = Hitting(form)
    return [hitting.hit() for _ in range(n)]


def terms(form: Form, n: int) -> list:
    """The first n terms of the sequence a form gives, its hits flattened, "thus giving the
    sequence: 1 2 1 2 3 1 2 3 4 ..." [M86 p. 56]. A form whose hits give no terms (an empty
    group) is stopped after n hits."""
    hitting = Hitting(form)
    out = []
    while len(out) < n and hitting.count <= 10 * n + 10:
        out.extend(flatten(hitting.hit()))
    return out[:n]
